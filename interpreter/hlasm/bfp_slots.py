# pyright: standard
"""Positions in a BFP builtin's result list, and the FPC mask, flag and DXC bits its trap and flag words use."""

SCALED_SLOT = 3
TRAP_SLOT = 6
FLAGS_SLOT = 7
SCALED_DXC_SLOT = 8
INEXACT_DXC_SLOT = 9
CC_SLOT = 10
QUOTIENT_SLOT = 11

INVALID_BIT = 0x80
DIVISION_BY_ZERO_BIT = 0x40
OVERFLOW_BIT = 0x20
UNDERFLOW_BIT = 0x10
INEXACT_BIT = 0x08
INCREMENTED_BIT = 0x04
SUPPRESSING_BITS = INVALID_BIT | DIVISION_BY_ZERO_BIT
SCALING_BITS = OVERFLOW_BIT | UNDERFLOW_BIT
