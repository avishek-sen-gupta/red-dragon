"""How a SORT or MERGE key's bytes are read for comparison."""

from __future__ import annotations

from enum import Enum


class SortKeyEncoding(Enum):
    ALPHANUMERIC = "ALPHANUMERIC"
    ZONED_TRAILING = "ZONED_TRAILING"
    ZONED_LEADING = "ZONED_LEADING"
    ZONED_TRAILING_SEPARATE = "ZONED_TRAILING_SEPARATE"
    ZONED_LEADING_SEPARATE = "ZONED_LEADING_SEPARATE"
    PACKED = "PACKED"
    BINARY_SIGNED = "BINARY_SIGNED"
    BINARY_UNSIGNED = "BINARY_UNSIGNED"
    FLOAT_SHORT = "FLOAT_SHORT"
    FLOAT_LONG = "FLOAT_LONG"
